window.CCT_t = function CCT_t(lang, path, vars) {
  const pack = window.CCT_I18N[lang] || window.CCT_I18N.ru;
  const fallback = window.CCT_I18N.ru;
  const pick = (obj, key) => key.split('.').reduce((o, k) => (o && o[k] != null ? o[k] : undefined), obj);
  let s = pick(pack, path) ?? pick(fallback, path) ?? path;
  if (vars && typeof s === 'string') {
    Object.keys(vars).forEach((k) => {
      s = s.split('{' + k + '}').join(vars[k]);
    });
  }
  return s;
};
